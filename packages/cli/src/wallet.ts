import { existsSync, appendFileSync } from "node:fs";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import type { Hex } from "viem";

const ENV_KEY = "TELEGRAPH_EVM_PRIVATE_KEY";

/**
 * Loads the miner's key from TELEGRAPH_EVM_PRIVATE_KEY, generating and
 * persisting a burner wallet into .env on first run if unset — mirrors
 * telegraph-mcp's key handling, except telegraph-mcp requires the operator
 * to supply one. Auto-generating is the "plug and play" half of the ask:
 * a developer with no wallet yet can still get to a registration.
 */
export function loadOrCreateWallet(cwd: string): { privateKey: Hex; address: `0x${string}`; created: boolean } {
  const existing = process.env[ENV_KEY];
  if (existing) {
    const key = existing as Hex;
    return { privateKey: key, address: privateKeyToAccount(key).address, created: false };
  }

  const key = generatePrivateKey();
  const address = privateKeyToAccount(key).address;

  const envPath = `${cwd}/.env`;
  const line = `${ENV_KEY}=${key}\n`;
  if (existsSync(envPath)) {
    appendFileSync(envPath, line);
  } else {
    appendFileSync(envPath, `# Generated by telegraph-miner init — keep this file out of git.\n${line}`, { mode: 0o600 });
  }

  return { privateKey: key, address, created: true };
}
